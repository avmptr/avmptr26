def seed():
    url = os.environ.get("DATABASE_URL", "")
    if not url:
        print("ERROR: set DATABASE_URL environment variable first.")
        print("  export DATABASE_URL=<your-railway-postgres-url>")
        return
    if url.startswith("postgres://"):
        url = url.replace("postgres://", "postgresql://", 1)

    conn = psycopg2.connect(url, cursor_factory=psycopg2.extras.RealDictCursor)
    cur = conn.cursor()

    psycopg2.extras.execute_batch(
        cur,
        "INSERT INTO trees (tree_code, block, row_num, plot_num, variety) "
        "VALUES (%s, %s, %s, %s, %s) ON CONFLICT DO NOTHING",
        TREES,
    )
    conn.commit()

    cur.execute("SELECT block, COUNT(*) AS n FROM trees GROUP BY block ORDER BY block")
    rows = cur.fetchall()
    print()
    for r in rows:
        label = "Sawah" if r["block"] == "SD" else f"Blok {r['block']}"
        print(f"  {label:12s}: {r['n']:3d} trees")
    cur.execute("SELECT COUNT(*) AS n FROM trees")
    total = cur.fetchone()["n"]
    print(f"\n  {'TOTAL':12s}: {total:3d} trees")
    cur.close()
    conn.close()


if __name__ == "__main__":
    seed()
